"""Convert the PNG files in this folder into the art shown on the displays.

Every PNG becomes a 68x68, 1 bit per pixel byte array in ../widgets/art/,
and art_list.h there lists them all. The firmware draws them pixel by pixel,
so this is a plain packed bitmap, not an LVGL image.

Run from anywhere:

    uv run app/boards/shields/borek_view/images/convert.py

Commit the generated files together with the PNGs; the firmware build does
not run this script.
"""

from __future__ import annotations

import re
from pathlib import Path

from PIL import Image, ImageOps

IMAGES_DIR = Path(__file__).resolve().parent
OUT_DIR = IMAGES_DIR.parent / "widgets" / "art"

IMG_W = 68
IMG_H = 68
ROW_BYTES = (IMG_W + 7) // 8

GENERATED = "/* Generated by images/convert.py. Do not edit. */\n"


def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return s or "img"


def to_1bit(png_path: Path) -> bytes:
    img = Image.open(png_path)
    img = ImageOps.exif_transpose(img)
    if img.mode != "RGBA":
        img = img.convert("RGBA")
    # Flatten transparency onto white, then crop to a centered square.
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    img = Image.alpha_composite(bg, img).convert("L")
    img = ImageOps.fit(img, (IMG_W, IMG_H), method=Image.LANCZOS)
    img = img.convert("1", dither=Image.FLOYDSTEINBERG)

    # Row by row, most significant bit first. A set bit is a foreground
    # pixel. The light pixels of the source become the foreground, so on the
    # default black-on-white display the picture comes out inverted.
    out = bytearray(ROW_BYTES * IMG_H)
    px = img.load()
    for y in range(IMG_H):
        for x in range(IMG_W):
            if px[x, y]:
                out[y * ROW_BYTES + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(out)


def emit_c(name: str, data: bytes) -> str:
    lines = [
        GENERATED,
        "// clang-format off\n",
        "#include <stdint.h>\n\n",
        f"const uint8_t {name}_data[] = {{\n",
    ]
    for y in range(IMG_H):
        row = data[y * ROW_BYTES : (y + 1) * ROW_BYTES]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in row) + ",\n")
    lines.append("};\n")
    return "".join(lines)


def emit_header(names: list[str]) -> str:
    lines = [
        GENERATED,
        "// clang-format off\n",
        "#pragma once\n\n",
        "#include <stdint.h>\n\n",
        f"#define ART_IMG_W {IMG_W}\n",
        f"#define ART_IMG_H {IMG_H}\n",
        f"#define ART_IMG_ROW_BYTES {ROW_BYTES}\n\n",
    ]
    lines += [f"extern const uint8_t {n}_data[];\n" for n in names]
    lines.append("\nstatic const uint8_t *const art_images[] = {\n")
    lines += [f"    {n}_data,\n" for n in names]
    lines.append("};\n\n")
    lines.append(f"#define ART_IMAGES_COUNT {len(names)}\n")
    return "".join(lines)


def write(path: Path, text: str) -> None:
    # Always LF, so regenerating on Windows does not rewrite every file.
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    pngs = sorted(IMAGES_DIR.glob("*.png"), key=lambda p: p.name.lower())
    if len(pngs) < 2:
        raise SystemExit(
            f"Need at least 2 PNGs in {IMAGES_DIR} (found {len(pngs)}): "
            "the two halves always show different images."
        )

    names = [f"img_{slug(png.stem)}" for png in pngs]
    if len(set(names)) != len(names):
        raise SystemExit(f"Two PNGs map to the same name: {sorted(names)}")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for stale in OUT_DIR.glob("img_*.c"):
        stale.unlink()

    for png, name in zip(pngs, names):
        write(OUT_DIR / f"{name}.c", emit_c(name, to_1bit(png)))
        print(f"  {png.name} -> {name}.c")

    write(OUT_DIR / "art_list.h", emit_header(names))
    print(f"Wrote {len(names)} images to {OUT_DIR}")


if __name__ == "__main__":
    main()
